// Writes src/Metered.Themes/Tokens/*.g.axaml from the pinned baseui package's LightTheme and
// DarkTheme: every value under Base Web's own name, as `<group>.<name>` (colors.buttonPrimaryFill,
// sizing.scale600, typography.LabelMedium.fontSize). Values that differ between the themes go in
// ThemeDictionaries; the rest are shared.
//
// Also writes Tokens/ButtonBoxShadows.g.axaml: each box-shadow Base Web's Button draws, per kind
// and state, from Base Web's own style function (tools/reference/oracle.js), because a BoxShadows
// value is parsed whole and can't hold a DynamicResource colour.
//
// And Theming/ThemeDerivation.g.cs: what Base Web's createTheme and createDarkTheme derive from the
// foundation colours, and what each Button shadow is made of (theme.js).
//
//   node tools/tokens/gen.js          write the files
//   node tools/tokens/gen.js --check  fail if a file would change
'use strict';

const fs = require('fs');
const path = require('path');
const css = require('../reference/css');
const { THEMES } = require('../reference/oracle');
const version = require('baseui/package.json').version;

const root = path.resolve(__dirname, '../..');
const outDir = path.join(root, 'src/Metered.Themes/Tokens');
const check = process.argv.includes('--check');

const header = (what) => `<!--
  Generated by tools/tokens/gen.js from baseui ${version} (© Uber Technologies, Inc., MIT). Do not edit.
  ${what}
-->
<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    xmlns:sys="using:System">
`;
const footer = '</ResourceDictionary>\n';
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

/** Writes shared entries, and ThemeDictionaries for the entries whose value differs. */
function dictionary(what, entries) {
  // entries: [{ key, element: (theme) => string }]
  const shared = [], varying = [];
  for (const e of entries) {
    (e.element(THEMES.Light) === e.element(THEMES.Dark) ? shared : varying).push(e);
  }
  let out = header(what);
  for (const e of shared) out += '  ' + e.element(THEMES.Light) + '\n';
  if (varying.length) {
    out += '  <ResourceDictionary.ThemeDictionaries>\n';
    for (const [name, theme] of Object.entries(THEMES)) {
      out += `    <ResourceDictionary x:Key="${name}">\n`;
      for (const e of varying) out += '      ' + e.element(theme) + '\n';
      out += '    </ResourceDictionary>\n';
    }
    out += '  </ResourceDictionary.ThemeDictionaries>\n';
  }
  return out + footer;
}

const files = {};

// Colours: 841 keys, the primitives included. The tag "RampUnit" entries are numbers, not colours.
files['Colors.g.axaml'] = dictionary('Every theme.colors value: a SolidColorBrush, or a string for the tag ramp units.',
  Object.keys(THEMES.Light.colors).map((name) => ({
    key: name,
    element: (t) => /RampUnit$/.test(name)
      ? `<x:String x:Key="colors.${name}">${esc(t.colors[name])}</x:String>`
      : `<SolidColorBrush x:Key="colors.${name}" Color="${css.color(t.colors[name])}" />`,
  })));

files['Sizing.g.axaml'] = dictionary('theme.sizing, in pixels.',
  Object.keys(THEMES.Light.sizing).map((name) => ({
    key: name,
    element: (t) => `<x:Double x:Key="sizing.${name}">${css.px(t.sizing[name])}</x:Double>`,
  })));

files['Borders.g.axaml'] = dictionary('theme.borders: the radii as CornerRadius, border100 to border600 as a width and a brush.',
  Object.entries(THEMES.Light.borders).flatMap(([name, v]) => {
    if (typeof v === 'boolean') {
      return [{ key: name, element: (t) => `<x:Boolean x:Key="borders.${name}">${t.borders[name] ? 'True' : 'False'}</x:Boolean>` }];
    }
    if (typeof v === 'string') {
      return [{ key: name, element: (t) => `<CornerRadius x:Key="borders.${name}">${css.px(t.borders[name])}</CornerRadius>` }];
    }
    return [
      { key: name + '.width', element: (t) => `<Thickness x:Key="borders.${name}.borderWidth">${css.px(t.borders[name].borderWidth)}</Thickness>` },
      { key: name + '.color', element: (t) => `<SolidColorBrush x:Key="borders.${name}.borderColor" Color="${css.color(t.borders[name].borderColor)}" />` },
    ];
  }));

files['Lighting.g.axaml'] = dictionary('theme.lighting, as BoxShadows.',
  Object.keys(THEMES.Light.lighting).map((name) => ({
    key: name,
    element: (t) => `<BoxShadows x:Key="lighting.${name}">${css.boxShadows(t.lighting[name])}</BoxShadows>`,
  })));

files['Animation.g.axaml'] = dictionary('theme.animation: the timings as TimeSpan, the curves as SplineEasing.',
  Object.keys(THEMES.Light.animation).map((name) => ({
    key: name,
    element: (t) => {
      const v = t.animation[name];
      if (/^cubic-bezier/.test(v)) {
        const [x1, y1, x2, y2] = css.cubicBezier(v);
        return `<SplineEasing x:Key="animation.${name}" X1="${x1}" Y1="${y1}" X2="${x2}" Y2="${y2}" />`;
      }
      return `<sys:TimeSpan x:Key="animation.${name}">${new Date(css.seconds(v) * 1000).toISOString().substr(11, 12)}</sys:TimeSpan>`;
    },
  })));

files['Typography.g.axaml'] = dictionary('theme.typography: each style\'s family, size, weight and line height.',
  Object.keys(THEMES.Light.typography).flatMap((name) => {
    const v = THEMES.Light.typography[name];
    if (typeof v === 'string') {
      return [{ key: name, element: (t) => `<FontFamily x:Key="typography.${name}">${esc(css.fontFamily(t.typography[name]))}</FontFamily>` }];
    }
    return [
      { key: name + 'f', element: (t) => `<FontFamily x:Key="typography.${name}.fontFamily">${esc(css.fontFamily(t.typography[name].fontFamily))}</FontFamily>` },
      { key: name + 's', element: (t) => `<x:Double x:Key="typography.${name}.fontSize">${css.px(t.typography[name].fontSize)}</x:Double>` },
      { key: name + 'w', element: (t) => `<FontWeight x:Key="typography.${name}.fontWeight">${css.fontWeight(t.typography[name].fontWeight)}</FontWeight>` },
      { key: name + 'l', element: (t) => `<x:Double x:Key="typography.${name}.lineHeight">${css.px(t.typography[name].lineHeight)}</x:Double>` },
    ];
  }));

// The themes of Checkbox's parts (checkbox.js).
files['../Controls/Checkbox.Parts.g.axaml'] = require('./checkbox').file(version);

// The Button's box-shadows (button-shadows.js).
const shadows = require('./button-shadows');
files['ButtonBoxShadows.g.axaml'] = dictionary(
  'The box-shadows of Base Web\'s Button, from its own style function: button.boxShadow.<kind>.<state>[.safe].',
  shadows.ALL.map(([kind, s, safe]) => ({
    key: `${kind}.${s}.${safe}`,
    element: (t) => `<BoxShadows x:Key="${shadows.key(kind, s, safe)}">${shadows.buttonShadow(t, kind, s, safe)}</BoxShadows>`,
  })));

files['../Controls/Button.Parts.g.axaml'] = require('./button').file(version);

// The themes of Radio's parts, from Base Web's radio-v2 (radio.js).
files['../Controls/Radio.Parts.g.axaml'] = require('./radio').file(version);

// The themes of Switch's parts, from Base Web's switch (switch.js).
files['../Controls/Switch.Parts.g.axaml'] = require('./switch').file(version);

// The themes of ProgressBar's parts, from Base Web's progress bar (progress-bar.js).
files['../Controls/ProgressBar.Parts.g.axaml'] = require('./progress-bar').file(version);
// The theme of Spinner's part, from Base Web's spinner (spinner.js).
files['../Controls/Spinner.Parts.g.axaml'] = require('./spinner').file(version);

// The themes of Input's parts, from Base Web's input and its icons (input.js).
files['../Controls/Input.Parts.g.axaml'] = require('./input').file(version);
// The themes of Textarea's parts, from Base Web's textarea and Input's BaseInput (textarea.js).
files['../Controls/Textarea.Parts.g.axaml'] = require('./textarea').file(version);
// The themes of FormControl's parts, from Base Web's form control and its two icons (form-control.js).
files['../Controls/FormControl.Parts.g.axaml'] = require('./form-control').file(version);
// The themes of Popover's parts, from Base Web's popover (popover.js).
files['../Controls/Popover.Parts.g.axaml'] = require('./popover').file(version);

// The themes of Slider's parts, from Base Web's slider, and its thumb's box-shadow, a literal colour there (slider.js).
const slider = require('./slider');
files['../Controls/Slider.Parts.g.axaml'] = slider.file(version);
files['SliderBoxShadows.g.axaml'] = dictionary(
  `The thumb's box-shadow in Base Web's Slider, a literal in its style function: ${slider.SHADOW_KEY}.`, slider.shadows);

// What createTheme and createDarkTheme derive, for Metered.Themes.Theme (theme.js).
files['../Theming/ThemeDerivation.g.cs'] = require('./theme').file(version);

fs.mkdirSync(outDir, { recursive: true });
let stale = [];
for (const [name, text] of Object.entries(files)) {
  const file = path.join(outDir, name);
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old === text) continue;
  if (check) stale.push(name);
  else { fs.writeFileSync(file, text); console.log('wrote', path.relative(root, file)); }
}
if (check && stale.length) { console.error('Out of date:', stale.join(', ')); process.exit(1); }
