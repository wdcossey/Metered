// The themes of Tooltip's parts, Tooltip.Styled<Part>, generated from Base Web's tooltip
// (baseui/tooltip/styled-components): Popover's style functions (getBodyStyles, getArrowStyles, getInnerStyles) with the
// tooltip's own values over them, evaluated by popover.js's helpers on a theme whose colours, radii and shadows are their
// own names, for every combination of the states popover.js gives the parts, written as the fewest state styles with
// the theme writer the other controls share (radio.js). The tests' oracle (tools/reference/tooltip.js) checks the result
// against the real colours.
//
// What differs from the Popover's (popover.js), and what the Tooltip gives (Metered.Controls.Tooltip):
// - Body: tooltipBackground, radius300, shadow400, tooltipText; its transition opacity alone and its transform getEndPosition in
//   every state, so it fades in where it is placed and never slides: the Tooltip gives no start (its BodySlides). Its
//   margin is still getPopoverMarginStyles', which the Popover gives, and a hover body's 0.1 s of not taking the pointer
//   is getBodyStyles' own.
// - Arrow: getArrowStyles in tooltipBackground; its shadow, box and side are the Popover's.
// - Inner: tooltipBackground, radius300, tooltipText, padding scale300 by scale600 and font150.
'use strict';

const sc = require('baseui/tooltip/styled-components');
const css = require('../reference/css');
const { check, colour, theme: write } = require('./radio');
const { padding, font } = require('./input');
const { AXES, T, token, flat, radius, entrance, hitTest, arrowPart, RADII, MARGINS } = require('./popover');

/** getEndPosition at popper.js's offset, which Metered gives the popup's position instead: no move. */
const END = 'translate3d(0px, 0px, 0)';
const FONT = ['fontFamily', 'fontSize', 'fontWeight', 'lineHeight'];
const PADDING = ['paddingTop', 'paddingBottom', 'paddingLeft', 'paddingRight'];
/** A ContentPresenter's own text properties. */
const OWN = { Foreground: 'Foreground', FontFamily: 'FontFamily', FontSize: 'FontSize', FontWeight: 'FontWeight', LineHeight: 'LineHeight' };

function parts() {
  return [
    {
      part: 'Body', type: 'Border',
      styled: (t, c) => flat(sc.Body, T, c),
      convert(s) {
        const what = 'Body';
        check(s, what, ['position', 'top', 'left', 'backgroundColor', ...RADII, 'boxShadow', 'color', 'transitionProperty', 'transitionDuration',
          'transitionTimingFunction', 'opacity', 'transform', ...MARGINS, 'animationDuration']);
        if (s.position !== 'absolute' || s.top !== 0 || s.left !== 0) throw new Error(`${what} box`);
        if (s.transitionProperty !== 'opacity') throw new Error(`${what} transitions ${s.transitionProperty}`);
        if (s.transform !== END) throw new Error(`${what} transform ${s.transform}`);
        return {
          Background: colour(s.backgroundColor, what), CornerRadius: radius(s, what), BoxShadow: token(s.boxShadow, what),
          // CSS's color is inherited: a Border passes it down as TextElement's.
          'TextElement.Foreground': colour(s.color, what), Opacity: String(s.opacity),
        };
      },
    },
    arrowPart(sc.Arrow),
    {
      part: 'Inner', type: 'ContentPresenter',
      styled: (t, c) => flat(sc.Inner, T, c),
      convert(s) {
        const what = 'Inner';
        check(s, what, ['backgroundColor', ...RADII, 'color', 'position', ...PADDING, ...FONT]);
        if (s.position !== 'relative') throw new Error(`${what} box`);
        return {
          Background: colour(s.backgroundColor, what), CornerRadius: radius(s, what), Padding: padding(s),
          Foreground: colour(s.color, what), ...font(s, what, OWN),
        };
      },
    },
  ];
}

const DESCRIBE = {
  Body: 'the box placed against the anchor: its fill, radius, shadow and text colour; its opacity and fade by state, in place.',
  Arrow: 'the arrow, a box turned 45° behind Inner: its fill, shadow, size, and the side it sits beyond by placement.',
  Inner: 'the content\'s box over the arrow: its fill, radius, padding, font and text colour.',
};

function file(version) {
  const themes = parts().map((p) => {
    const { plain, blocks } = write(p, AXES, (styled, t, c) => styled(t, c), { layered: true });
    const extra = p.part === 'Body' ? [entrance(sc.Body), hitTest(sc.Body)] : [];
    const body = [...plain, ...extra, ...blocks];
    return `  <!-- ${p.part}: ${DESCRIBE[p.part]} -->
  <ControlTheme x:Key="Tooltip.Styled${p.part}" TargetType="${p.type}">\n${body.join('\n')}\n  </ControlTheme>`;
  });
  return `<!--
  Generated by tools/tokens/gen.js (tools/tokens/tooltip.js) from baseui ${version}
  (© Uber Technologies, Inc., MIT). Do not edit.
  The themes of Tooltip's parts, Tooltip.Styled<Part>, from Base Web's tooltip: the Popover's style functions with the
  tooltip's own values over them, each part's look by the state pseudoclasses the Popover mirrors onto it
  (Metered.Controls.Tooltip), the colours, radii, shadows and font by token, the lengths read from Base Web's own style
  functions.
-->
<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    xmlns:b="https://github.com/wdcossey/Metered">
${themes.join('\n')}
</ResourceDictionary>
`;
}

module.exports = { file, parts };
